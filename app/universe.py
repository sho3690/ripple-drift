def clean_jp_name(name: str) -> str:
    """EDINET の提出者名から法人格を落として表示用にする。"""
    n = name.replace("株式会社", "").replace("（株）", "").replace("(株)", "").replace("㈱", "")
    return n.strip("　 ")


def register_dynamic(rows: list[dict], jp_names: dict[str, str]) -> list[Node]:
    """スクリーナー由来の銘柄を Node 化して NODE_BY_SYMBOL に登録（seed は上書きしない）。"""
    added: list[Node] = []
    for r in rows:
        sym = r["symbol"]
        if sym in NODE_BY_SYMBOL:
            continue
        jp = jp_names.get(sym)
        name = clean_jp_name(jp) if jp else r.get("name_en", sym)
        node = Node(sym, name, "JP", r.get("sector") or "—", True)
        NODE_BY_SYMBOL[sym] = node
        added.append(node)
    return added


def _e(supplier: str, customer: str, w: float, source: str, note: str = "") -> Edge:
    return Edge(supplier, customer, w, source, note)


