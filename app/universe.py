@dataclass(frozen=True)
class Edge:
    supplier: str
    customer: str
    weight: float        # 売上依存度（0-1）
    source: str          # edinet / apple / public
    note: str = ""


def _jp(code: str, name: str, sector: str) -> Node:
    return Node(f"{code}.T", name, "JP", sector, True)


def _foreign(symbol: str, name: str, market: str, sector: str) -> Node:
    return Node(symbol, name, market, sector, False)


